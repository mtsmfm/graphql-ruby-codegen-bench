# Generate a standalone GraphQL executor (no graphql-ruby at runtime) from a
# graphql-ruby schema. Runs on CRuby.
#
#   ruby tools/gen_executor.rb SCHEMA_FILE SCHEMA_CONST MODELS_FILE OUT
#
# The output requires runtime/gql_runtime.rb and MODELS_FILE, and defines
# gql_execute(query_string, variables, context) returning the result hash.
require "pathname"
require "prism"

schema_file, schema_const, models_file, out_path = ARGV
abort "usage: gen_executor.rb SCHEMA_FILE SCHEMA_CONST MODELS_FILE OUT" unless out_path
require File.expand_path(schema_file)
schema = Object.const_get(schema_const)
GRAPHQL_LIB = File.dirname(GraphQL.method(:parse).source_location[0])

BUILTIN_SCALARS = %w[String Int Float Boolean ID].freeze

types = schema.types.reject { |name, _| name.start_with?("__") }
objects = types.values.select { |t| t.kind.object? }
enums = types.values.select { |t| t.kind.enum? }
types.each_value do |t|
  next if t.kind.object? || t.kind.enum?
  next if t.kind.scalar? && BUILTIN_SCALARS.include?(t.graphql_name)
  # Interfaces only contribute fields to the objects implementing them
  # (graphql-ruby copies those into each object's #fields); returning one
  # would need resolve_type, which is checked per field below.
  next if t.kind.interface?
  abort "unsupported type kind for #{t.graphql_name}: #{t.kind.name}"
end

# Application lazy classes (`lazy_resolve Proc, :call`): graphql-ruby syncs
# such values wherever a field value or list item appears, repeatedly
# (Schema.sync_lazy recurses), so the generated code does the same in place.
# GQL_ABLATE=plan,dispatch,complete,lazy puts back one of graphql-ruby's
# generic mechanisms each (timing experiments; default output is unchanged):
#   plan     - build the child selection plan for every object, not once per field
#   dispatch - wrap every object in its type class, resolve by name (hash_key,
#              respond_to?, public_send) like Field#resolve
#   complete - complete values by walking a runtime type description (case kind)
#   lazy     - pass every field value through an after_lazy-style block
ABLATE = ENV["GQL_ABLATE"].to_s.split(",")
# GQL_STRICT=1 keeps graphql-ruby's Int range and String encoding checks in result coercion.
STRICT = ENV["GQL_STRICT"] == "1"
unknown = ABLATE - %w[plan dispatch complete lazy]
abort "unknown GQL_ABLATE: #{unknown.join(",")}" unless unknown.empty?
LAZY = []
schema.send(:lazy_methods).each do |klass, meth|
  LAZY << [klass.name, meth] if meth && !klass.name.to_s.start_with?("GraphQL::")
end

def rb_ident(name)
  name.gsub(/[^A-Za-z0-9_]/, "_")
end

def type_sig(t)
  t.to_type_signature
end

# --- resolver classes: user-defined instance methods copied from source ---
def user_method?(owner, name)
  return false unless owner.method_defined?(name) || owner.private_method_defined?(name)
  loc = owner.instance_method(name).source_location
  loc && !loc[0].start_with?(GRAPHQL_LIB)
end

# Source of a user-defined method, and the modules lexically around it (so
# constants it names, like a module's DATA, still resolve once copied).
def def_source(um)
  file, line = um.source_location
  @prism_cache ||= {}
  root = (@prism_cache[file] ||= Prism.parse_file(file).value)
  found = nil
  nesting = nil
  stack = [[root, []]]
  until stack.empty? || found
    node, mods = stack.pop
    if node.is_a?(Prism::DefNode) && node.name == um.name && node.location.start_line == line
      found = node
      nesting = mods
    else
      inner = node.is_a?(Prism::ModuleNode) ? mods + [node.constant_path.slice] : mods
      node.compact_child_nodes.each { |c| stack << [c, inner] }
    end
  end
  abort "cannot find source for #{um.owner}##{um.name}" unless found
  # Re-indent to two spaces (class body level).
  shift = found.location.start_column - 2
  lines = found.slice.lines
  [([lines[0]] + lines.drop(1).map { |l| l.start_with?(" " * shift) ? l[shift..] : l }).join, nesting]
end

out = +""
out << "# GENERATED by tools/gen_executor.rb from #{schema_const} -- do not edit.\n"
# require_relative paths relative to the output file, so the generated code can move with its directory
out_dir = Pathname(File.expand_path(File.dirname(out_path)))
rel = ->(path) { Pathname(File.expand_path(path)).relative_path_from(out_dir).to_s.delete_suffix(".rb") }
out << "require_relative #{rel.(File.expand_path("../runtime/gql_runtime", __dir__)).inspect}\n"
out << "require_relative #{rel.(models_file).inspect}\n\n"

resolver_class = {}
objects.each do |obj|
  user_ancestors = obj.ancestors.take_while { |a| a != GraphQL::Schema::Object }.select { |a| a.is_a?(Class) || a.is_a?(Module) }
  defs = []
  nesting = nil
  user_ancestors.each do |anc|
    # in source order, so the output is the same on every run
    ms = (anc.instance_methods(false) + anc.private_instance_methods(false)).select { |m| user_method?(anc, m) }
    ms.sort_by { |m| anc.instance_method(m).source_location }.each do |m|
      src, mods = def_source(anc.instance_method(m))
      abort "#{obj.graphql_name}: resolver methods from different modules" if nesting && nesting != mods
      nesting = mods
      defs << src
    end
  end
  next if defs.empty?
  cname = "GQLR_#{rb_ident(obj.graphql_name)}"
  resolver_class[obj] = (nesting + [cname]).join("::")
  nesting.each { |m| out << "module #{m}\n" }
  out << "class #{cname}\n"
  out << "  def initialize(object, context)\n    @object = object\n    @context = context\n  end\n\n"
  out << "  def object\n    @object\n  end\n\n  def context\n    @context\n  end\n"
  defs.each { |src| out << "\n  " << src.chomp << "\n" }
  out << "end\n"
  nesting.each { out << "end\n" }
  out << "\n"
end

# --- schema metadata for the validator ---
out << "def schema_root_type(op_type)\n"
%w[query mutation subscription].each do |op|
  root = schema.public_send(op)
  out << "  return #{root.graphql_name.inspect} if op_type == #{op.inspect}\n" if root
end
out << "  \"\"\nend\n\n"

out << "def schema_type_kind(name)\n  case name\n"
types.each_value { |t| out << "  when #{t.graphql_name.inspect} then #{t.kind.name.inspect}\n" }
out << "  else \"\"\n  end\nend\n\n"

out << "def schema_field_type(parent, name)\n"
objects.each do |obj|
  out << "  if parent == #{obj.graphql_name.inspect}\n    case name\n"
  obj.fields.each_value { |f| out << "    when #{f.graphql_name.inspect} then return #{type_sig(f.type).inspect}\n" }
  out << "    end\n  end\n"
end
out << "  \"\"\nend\n\n"

out << "def schema_field_args(parent, name)\n"
objects.each do |obj|
  with_args = obj.fields.values.reject { |f| f.arguments.empty? }
  next if with_args.empty?
  out << "  if parent == #{obj.graphql_name.inspect}\n    case name\n"
  with_args.each { |f| out << "    when #{f.graphql_name.inspect} then return #{f.arguments.keys.inspect}\n" }
  out << "    end\n  end\n"
end
out << "  []\nend\n\n"

out << "def schema_arg_type(parent, field, arg)\n"
out << "  schema_arg_info(parent, field, arg, false)\nend\n\n"
out << "def schema_arg_has_default(parent, field, arg)\n"
out << "  schema_arg_info(parent, field, arg, true) == \"y\"\nend\n\n"
arg_whens = []
objects.each do |obj|
  obj.fields.each_value do |f|
    f.arguments.each_value do |a|
      arg_whens << "  when #{"#{obj.graphql_name}.#{f.graphql_name}.#{a.graphql_name}".inspect} then want_default ? #{(a.default_value? ? "y" : "n").inspect} : #{type_sig(a.type).inspect}\n"
    end
  end
end
out << "def schema_arg_info(parent, field, arg, want_default)\n"
if arg_whens.empty?  # a `case` with no `when` is a syntax error
  out << "  \"\"\nend\n\n"
else
  out << "  key = parent + \".\" + field + \".\" + arg\n  case key\n" << arg_whens.join << "  else \"\"\n  end\nend\n\n"
end

out << "def schema_enum_has(type, value)\n"
enums.each do |e|
  out << "  return #{e.values.keys.inspect}.include?(value) if type == #{e.graphql_name.inspect}\n"
end
out << "  false\nend\n\n"

# --- enum conversions ---
enums.each do |e|
  n = rb_ident(e.graphql_name)
  out << "def enum_in_#{n}(name)\n  case name\n"
  e.values.each_value { |v| out << "  when #{v.graphql_name.inspect} then #{v.value.inspect}\n" }
  out << "  end\nend\n\n"
  out << "def enum_out_#{n}(value)\n  case value\n"
  e.values.each_value { |v| out << "  when #{v.value.inspect} then #{v.graphql_name.inspect}\n" }
  out << "  end\nend\n\n"
end

# --- executor ---
class Emitter
  def initialize
    @n = 0
  end

  def fresh(prefix)
    @n += 1
    "#{prefix}#{@n}"
  end

  # Emit code that completes value `v` of type `t` into a new local and
  # return its name. When t is non-null and the value (or a propagated child)
  # is null, `on_invalid` runs.
  def complete(t, v, lines, ind, on_invalid, err)
    LAZY.each do |klass, meth|
      lines << "#{ind}while #{v}.is_a?(#{klass})"
      lines << "#{ind}  #{v} = #{v}.#{meth}"
      lines << "#{ind}end"
    end
    if t.non_null?
      lines << "#{ind}if #{v}.nil?"
      lines << "#{ind}  #{err}"
      lines << "#{ind}  #{on_invalid}"
      lines << "#{ind}end"
      inner = t.of_type
      r = complete_inner(inner, v, lines, ind, err)
      if inner.list? || inner.kind.object?
        if inner.kind.object?
          # evaluate the child once; the result is checked and then stored
          ro = fresh("o")
          lines << "#{ind}#{ro} = #{r}"
          r = ro
        end
        lines << "#{ind}if #{r}.nil?"
        lines << "#{ind}  #{on_invalid}"
        lines << "#{ind}end"
      end
      r
    else
      r = fresh("r")
      lines << "#{ind}#{r} = nil"
      lines << "#{ind}unless #{v}.nil?"
      rr = complete_inner(t, v, lines, ind + "  ", err)
      lines << "#{ind}  #{r} = #{rr}"
      lines << "#{ind}end"
      r
    end
  end

  def complete_inner(t, v, lines, ind, err)
    if t.list?
      arr = fresh("arr")
      ok = fresh("ok")
      i = fresh("i")
      item = fresh("item")
      lines << "#{ind}#{arr} = []"
      lines << "#{ind}#{ok} = true"
      lines << "#{ind}#{i} = 0"
      lines << "#{ind}while #{i} < #{v}.size"
      lines << "#{ind}  @path.push(#{i})"
      lines << "#{ind}  #{item} = #{v}[#{i}]"
      elem_err = err.sub(/\A(?:leaf_)?null_error\((.*?), f(?:, key)?\)\z/) { "null_element_error(#{$1}, #{type_sig(t.of_type).inspect}, f)" }
      ri = complete(t.of_type, item, lines, ind + "  ", "@path.pop; #{ok} = false; break", elem_err)
      lines << "#{ind}  #{arr} << #{ri}"
      lines << "#{ind}  @path.pop"
      lines << "#{ind}  #{i} += 1"
      lines << "#{ind}end"
      res = fresh("l")
      lines << "#{ind}#{res} = #{ok} ? #{arr} : nil"
      res
    elsif t.kind.object?
      if ABLATE.include?("plan")
        "exec_#{rb_ident(t.graphql_name)}(#{v}, plan_#{rb_ident(t.graphql_name)}(e.sub))"
      else
        "exec_#{rb_ident(t.graphql_name)}(#{v}, cp)"
      end
    elsif t.kind.enum?
      "enum_out_#{rb_ident(t.graphql_name)}(#{v})"
    else
      case t.graphql_name
      when "String" then STRICT ? "gql_str_out(#{v})" : "#{v}.to_s"
      when "ID" then "#{v}.to_s"
      when "Int" then STRICT ? "gql_int_out(#{v})" : "#{v}.to_i"
      when "Float" then "#{v}.to_f"
      when "Boolean" then v
      end
    end
  end
end

def arg_reader(type, a)
  base = type.unwrap
  abort "list arguments are not supported yet" if type.list? || (type.non_null? && type.of_type.list?)
  if base.kind.enum?
    "enum_in_#{rb_ident(base.graphql_name)}(arg_str(#{a}))"
  else
    case base.graphql_name
    when "Int" then "arg_int(#{a})"
    when "Float" then "arg_float(#{a})"
    when "String", "ID" then "arg_str(#{a})"
    when "Boolean" then "arg_bool(#{a})"
    else abort "unsupported argument type #{base.graphql_name}"
    end
  end
end

# Runtime type descriptions for GQL_ABLATE=complete.
module GenericTypes
  @consts = {}
  def self.const(t)
    sig = t.to_type_signature
    @consts[sig] ||= ["GQLT_#{@consts.size}", t]
    @consts[sig][0]
  end

  def self.emit(t)
    if t.non_null? then "GQLT.new(\"NON_NULL\", \"\", #{emit(t.of_type)})"
    elsif t.list? then "GQLT.new(\"LIST\", \"\", #{emit(t.of_type)})"
    else "GQLT.new(#{t.kind.name.inspect}, #{t.graphql_name.inspect}, nil)"
    end
  end

  def self.source(objects, enums)
    out = +"GQL_PROP = Object.new\n"
    out << "class GQLT\n  attr_reader :kind, :name, :of\n  def initialize(kind, name, of)\n    @kind = kind\n    @name = name\n    @of = of\n  end\nend\n"
    @consts.each_value { |(name, t)| out << "#{name} = #{emit(t)}\n" }
    out << "\nclass GQLExecutor\n"
    out << "  # continue_value / continue_field: decide by the type's kind at run time\n"
    out << "  def gql_complete_generic(t, v, e)\n"
    LAZY.each { |klass, meth| out << "    while v.is_a?(#{klass})\n      v = v.#{meth}\n    end\n" }
    out << <<~RUBY.gsub(/^/, "    ")
      if t.kind == "NON_NULL"
        return GQL_PROP if v.nil?
        r = gql_complete_generic(t.of, v, e)
        return GQL_PROP if r.nil? || GQL_PROP.equal?(r)
        return r
      end
      return nil if v.nil?
      case t.kind
      when "LIST"
        arr = []
        i = 0
        while i < v.size
          ri = gql_complete_generic(t.of, v[i], e)
          return nil if GQL_PROP.equal?(ri)
          arr << ri
          i += 1
        end
        arr
      when "SCALAR"
        case t.name
        when "String", "ID" then v.to_s
        when "Int" then v.to_i
        when "Float" then v.to_f
        else v
        end
      when "ENUM"
        gql_enum_out(t.name, v)
      when "OBJECT"
        gql_exec_object(t.name, v, e)
      end
    RUBY
    out << "  end\n\n  def gql_enum_out(type, v)\n"
    if enums.empty?
      out << "    v\n"
    else
      out << "    case type\n"
      enums.each { |en| out << "    when #{en.graphql_name.inspect} then enum_out_#{rb_ident(en.graphql_name)}(v)\n" }
      out << "    end\n"
    end
    out << "  end\n\n  def gql_exec_object(type, v, e)\n    case type\n"
    objects.each do |o|
      id = rb_ident(o.graphql_name)
      plan = ABLATE.include?("plan") ? "plan_#{id}(e.sub)" : "(e.child ||= plan_#{id}(e.sub))"
      out << "    when #{o.graphql_name.inspect} then exec_#{id}(v, #{plan})\n"
    end
    out << "    end\n  end\nend\n\n"
  end
end

em = Emitter.new
out << "def type_applies?(cond, type_name)\n  cond == type_name\nend\n\n"
out << "class GQLExecutor < GQLExecutorBase\n"
objects.each do |obj|
  tname = obj.graphql_name
  id = rb_ident(tname)
  fields = obj.fields.values
  # plan builder + field-name -> id
  out << "  def fid_#{id}(name)\n    case name\n    when \"__typename\" then 0\n"
  fields.each_with_index { |f, i| out << "    when #{f.graphql_name.inspect} then #{i + 1}\n" }
  out << "    else -1\n    end\n  end\n\n"
  out << "  def plan_#{id}(sels)\n    groups = {}\n    collect_fields(#{tname.inspect}, sels, groups)\n"
  out << "    plan = GQLPlan.new\n    keys = groups.keys\n    i = 0\n    while i < keys.size\n"
  out << "      key = keys[i].to_s\n      fs = groups[key]\n      f = fs[0]\n      plan.add(key, fid_#{id}(f.name), f, merged_sels(fs))\n      i += 1\n    end\n    plan\n  end\n\n"

  rcls = resolver_class[obj]
  out << "  def exec_#{id}(obj, plan)\n    res = {}\n"
  out << "    r = nil\n" if rcls
  out << "    e = plan.first\n    until e.nil?\n"
  out << "      key = e.key\n      case e.fid\n      when 0\n        res[key] = #{tname.inspect}\n"
  fields.each_with_index do |field, fi|
    lines = []
    ind = "        "
    composite = field.type.unwrap.kind.object? || field.type.list?
    needs_f = composite || field.type.non_null? || !field.arguments.empty?
    lines << "#{ind}f = e.field" if needs_f
    kwargs = []
    field.arguments.each_value do |arg|
      a = em.fresh("a")
      k = em.fresh("k_#{arg.keyword}_")
      lines << "#{ind}#{a} = find_arg(f, #{arg.graphql_name.inspect})"
      reader = arg_reader(arg.type, a)
      if arg.type.non_null? && arg.default_value?
        # `Int! = 1000`: absent means the default (validation rejects null)
        lines << "#{ind}#{k} = #{a}.nil? ? #{arg.default_value.inspect} : #{reader}"
      elsif arg.type.non_null?
        lines << "#{ind}#{k} = #{reader}"
      else
        dflt = arg.default_value? ? arg.default_value.inspect : "nil"
        lines << "#{ind}#{k} = #{a}.nil? ? #{dflt} : (arg_null?(#{a}) ? nil : #{reader})"
      end
      kwargs << "#{arg.keyword}: #{k}"
    end
    call_args = kwargs.empty? ? "" : "(#{kwargs.join(", ")})"
    abort "#{tname}.#{field.graphql_name}: resolver classes are not supported" if field.resolver
    abort "#{tname}.#{field.graphql_name}: abstract return types are not supported" if field.type.unwrap.kind.abstract?
    field.extensions.each do |ext|
      noop = if ext.is_a?(GraphQL::Schema::Field::ScopeExtension)
        # added to every list field; it only calls the type's scope_items
        field.type.unwrap.method(:scope_items).owner == GraphQL::Schema::Member::Scoped
      else
        %i[resolve after_resolve apply].all? { |m| ext.class.instance_method(m).owner == GraphQL::Schema::FieldExtension }
      end
      abort "#{tname}.#{field.graphql_name}: field extension #{ext.class} is not supported" unless noop
    end
    v = em.fresh("v")
    hk = (field.hash_key.is_a?(Symbol) || field.hash_key.is_a?(String)) ? field.hash_key.to_sym : nil
    resolve_line = lines.size
    if ABLATE.include?("dispatch")
      inst = rcls ? "(r = #{rcls}.new(obj, @context) if r.nil?; r)" : "nil"
      kw = "{" + field.arguments.each_value.zip(kwargs).map { |_, kv| kv }.join(", ") + "}"
      lines << "#{ind}#{v} = gql_resolve_generic(obj, #{inst}, #{field.resolver_method.inspect}, #{hk.inspect}, #{kw})"
      resolve_line = lines.size - 1
    elsif hk
      # graphql-ruby tries the Symbol key, then the String key; the generated
      # code assumes Symbol-keyed Hashes.
      lines << "#{ind}#{v} = obj[#{hk.inspect}]"
      resolve_line = lines.size - 1
    elsif rcls && user_method?(field.owner, field.resolver_method)
      lines << "#{ind}r = #{rcls}.new(obj, @context) if r.nil?"
      lines << "#{ind}#{v} = r.#{field.resolver_method}#{call_args}"
      resolve_line = lines.size - 1
    else
      lines << "#{ind}#{v} = obj.#{field.method_sym}#{call_args}"
      resolve_line = lines.size - 1
    end
    if field.type.unwrap.kind.object?
      child = rb_ident(field.type.unwrap.graphql_name)
      lines << "#{ind}cp = e.child"
      lines << "#{ind}if cp.nil?"
      lines << "#{ind}  cp = plan_#{child}(e.sub)"
      lines << "#{ind}  e.child = cp"
      lines << "#{ind}end"
    end
    if ABLATE.include?("complete")
      cv = em.fresh("c")
      lines << "#{ind}#{cv} = gql_complete_generic(#{GenericTypes.const(field.type)}, #{v}, e)"
      lines << "#{ind}return nil if GQL_PROP.equal?(#{cv})"
      lines << "#{ind}res[key] = #{cv}"
    elsif composite
      lines << "#{ind}@path.push(key)"
      err = "null_error(#{tname.inspect}, #{field.graphql_name.inspect}, f)"
      r = em.complete(field.type, v, lines, ind, "@path.pop; return nil", err)
      lines << "#{ind}@path.pop"
    else
      err = "leaf_null_error(#{tname.inspect}, #{field.graphql_name.inspect}, f, key)"
      r = em.complete(field.type, v, lines, ind, "return nil", err)
    end
    lines << "#{ind}res[key] = #{r}" unless ABLATE.include?("complete")
    if ABLATE.include?("lazy")
      # everything after resolving the value runs in a block, as under after_lazy
      lz = em.fresh("lz")
      rest = lines.slice!((resolve_line + 1)..)
      lines << "#{ind}gql_after_lazy(#{v}) do |#{lz}|"
      lines << "#{ind}  #{v} = #{lz}"
      rest.each { |l| lines << "  #{l}" }
      lines << "#{ind}end"
    end
    out << "      when #{fi + 1}\n" << lines.join("\n") << "\n"
  end
  out << "      end\n      e = e.next_entry\n    end\n    res\n  end\n\n"
end
out << "end\n\n"

if ABLATE.include?("complete")
  out << GenericTypes.source(objects, enums)
end
if ABLATE.include?("dispatch")
  out << <<~RUBY
    class GQLExecutor
      # Field#resolve: hash_key, then a type method, then a Hash key, then a method on the object
      def gql_resolve_generic(obj, inst, meth, hash_key, kwargs)
        if !hash_key.nil?
          obj.is_a?(Hash) ? (obj.key?(hash_key) ? obj[hash_key] : obj[hash_key.to_s]) : obj[hash_key]
        elsif !inst.nil? && inst.respond_to?(meth)
          kwargs.empty? ? inst.public_send(meth) : inst.public_send(meth, **kwargs)
        elsif obj.is_a?(Hash)
          obj.key?(meth) ? obj[meth] : obj[meth.to_s]
        else
          kwargs.empty? ? obj.public_send(meth) : obj.public_send(meth, **kwargs)
        end
      end
    end

  RUBY
