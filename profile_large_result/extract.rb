# Cut graphql-ruby's benchmark/run.rb ProfileLargeResult into two files,
# without editing a line (only the one-level indent is removed):
#   data.rb   - eager_or_proc, DATA_SIZE, DATA (SecureRandom), for the Spinel binary
#   schema.rb - data.rb + the types, Schema and the two documents, for graphql-ruby
#
#   ruby extract.rb path/to/graphql-ruby/benchmark/run.rb
src = File.readlines(ARGV.fetch(0))
start = src.index("  module ProfileLargeResult\n") or abort "module ProfileLargeResult not found"
split = (start...src.size).find { |i| src[i] == "    module Bar\n" } or abort "module Bar not found"
stop = (start...src.size).find { |i| src[i] == "  end\n" } or abort "end of module not found"
body = ->(range) { src[range].map { |l| l.sub(/\A  /, "") }.join }
header = "# GENERATED by extract.rb from graphql-ruby benchmark/run.rb lines %d-%d -- do not edit.\n"
File.write("data.rb", format(header, start + 2, split) + "require \"securerandom\"\n\n" +
  "module ProfileLargeResult\n" + body.(start + 1...split) + "end\n")
File.write("schema.rb", format(header, split + 1, stop) + "require \"graphql\"\nrequire_relative \"data\"\n\n" +
  "module ProfileLargeResult\n" + body.(split...stop) + "end\n")
warn "data.rb: run.rb #{start + 2}-#{split}, schema.rb: run.rb #{split + 1}-#{stop}"
